"""Build the app's static catalogue from 60 reviewed ERA5 months and POWER summaries."""
import calendar
import json
import math
import re
import sys
from pathlib import Path

START, END = 2021, 2025

def record(i, month, monthly, power):
    # ERA5 precipitation rate kg/m²/s equals liquid-equivalent mm/s.
    rows = [(y, (y - START) * 12 + month - 1) for y in range(START, END + 1)]
    mean = lambda name, f: sum(f(monthly[name][j][i], y) for y, j in rows) / len(rows)
    rain = power["months"][str(month)]
    result = {
        "tmean": round(mean("t2m", lambda k, _: k - 273.15), 1),
        "tmax": round(mean("t2m_max", lambda k, _: k - 273.15), 1),
        "precipMm": round(mean("pr", lambda v, y: v * 86400 * calendar.monthrange(y, month)[1]), 1),
        "snowWaterMm": round(mean("snd", lambda v, _: v * 1000), 1),
        "rainDays": rain["rainDays"],
        "sunHours": rain["sunHours"],
    }
    numeric = [v for v in result.values() if v is not None]
    if not all(math.isfinite(x) for x in numeric):
        raise ValueError("non-finite weather")
    if not (-85 <= result["tmean"] <= result["tmax"] + 0.1 <= 65):
        raise ValueError("invalid average/maximum temperature")
    if not 0 <= result["rainDays"] <= calendar.monthrange(2024, month)[1] or any(result[k] < 0 for k in ("precipMm", "snowWaterMm")):
        raise ValueError("invalid precipitation or snowpack")
    if result["sunHours"] is not None and not 0 <= result["sunHours"] <= 24 * calendar.monthrange(2024, month)[1]:
        raise ValueError("invalid sunshine estimate")
    return result

def main():
    centers = json.loads(Path(sys.argv[1]).read_text())
    era = json.loads(Path(sys.argv[2]).read_text())
    power = Path(sys.argv[3])
    if era.get("period") != [START, END] or era.get("centers") != centers or not re.fullmatch(r"[A-Z0-9]{20}", era.get("snapshot", "")):
        raise ValueError("check ERA5 period, source snapshot and exact centre ordering")
    monthly = era["monthly"]
    for variable in ("t2m", "t2m_max", "pr", "snd"):
        if len(monthly[variable]) != 60 or any(len(row) != len(centers) for row in monthly[variable]):
            raise ValueError(f"incomplete ERA5 matrix: {variable}")
    rows, versions, missing_sun = [], set(), 0
    for i, place in enumerate(centers):
        id = place["id"]
        if not re.fullmatch(r"[a-z0-9-]+", id):
            raise ValueError("invalid region ID")
        p = json.loads((power / (id + ".json")).read_text())
        if p.get("period") != [START, END] or p.get("coordinates") != [place["lat"], place["lon"]]:
            raise ValueError("wrong POWER year or location: " + id)
        grid_lat, grid_lon = era["grid"][i]
        lon_diff = (grid_lon - place["lon"] + 180) % 360 - 180
        if abs(grid_lat - place["lat"]) > .126 or abs(lon_diff) > .126:
            raise ValueError("outside nearest ERA5 grid tolerance: " + id)
        versions.add(p["version"] or "미확인")
        months = {m: record(i, m, monthly, p) for m in range(1, 13)}
        missing_sun += sum(v["sunHours"] is None for v in months.values())
        rows.append(f"  {json.dumps(id)}: {json.dumps(months, separators=(',',':'), allow_nan=False)},")
    out = (
        "// Generated by scripts/build-recent-climate.py; do not edit by hand.\n"
        f"// Sources: docs/climate-data.md; ERA5 snapshot {era['snapshot']}; NASA POWER API {', '.join(sorted(versions))}.\n"
        'import type { MonthWeather } from "./regionsV1";\n\n'
        'export const WORLD_WEATHER_SOURCE = "ERA5 · NASA POWER 기반 2021–2025년 월별 기후 통계";\n'
        "export const WORLD_WEATHER: Record<string, Record<number, MonthWeather & { tmean: number; precipMm: number; snowWaterMm: number }>> = {\n"
        + "\n".join(rows) + "\n};\n"
    )
    Path(sys.argv[4]).write_text(out, encoding="utf-8")
    print(f"{len(rows)} regions × 12 months, missing estimated sunshine cells: {missing_sun}")

if __name__ == "__main__":
    main()
